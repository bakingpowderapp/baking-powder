use crate::Kind;

pub(crate) fn description(kind: Kind, key: &str) -> Option<&'static str> {
    Some(match (kind, key) {
        (Kind::Compressor | Kind::Sidechain, "peakDetector") => "true follows peaks; false, a 10 ms RMS average",
        (Kind::Compressor, "sumDetector") => "true sums the channels; false follows the louder one",
        (Kind::Compressor, "branching") => "separate attack and release smoothing; false, attackMs smooths both",
        (Kind::Compressor | Kind::Delay | Kind::Reverb, "dry") => "dry kept as wet rises; 0 crossfades, 1 keeps full dry",
        (Kind::Delay, "mode") => "echo mode: clean, tape or bbd",
        (Kind::Delay, "feedback") => "left feedback; the right line follows until rightFeedback is written",
        (Kind::Delay, "rightFeedback") => "right feedback; follows feedback until written",
        (Kind::Delay, "pingPong") => "left-to-right feedback share; the right line follows until rightPingPong is written",
        (Kind::Delay, "rightPingPong") => "right-to-left feedback share; follows pingPong until written",
        (Kind::Delay, "evenStereo") => "with evenPingPong, keeps a stereo input stereo",
        (Kind::Delay, "evenSway") => "with evenPingPong, one modulation pass per ping-pong pair; false, both lines modulate",
        (Kind::Delay, "drive") => "loop saturation in the tape and bbd modes",
        (Kind::Delay, "leftPan") => "left echo pan before width; its level at centre follows linePanBalance",
        (Kind::Delay, "rightPan") => "right echo pan before width; its level at centre follows linePanBalance",
        (Kind::Delay | Kind::Reverb, "duckGate") => "positive ducks above duckThresholdDb; negative gates, opening above it",
        (Kind::Delay, "followThresholdDb") => "follower threshold; the follower is full followRangeDb above it",
        (Kind::Delay, "followRangeDb") => "follower range above followThresholdDb",
        (Kind::Delay, "spliceLengthMs") => "splice length; adds about its own length of delay, or half with spliceSweep",
        (Kind::Delay, "spliceSmoothingMs") => "splice crossfade, at most half the splice length, or all of it with spliceSweep",
        (Kind::Delay, "spliceSweep") => "continuous pitch/reverse sweep across the splice length; no gaps between splices",
        (Kind::Freak, "dry") => "dry kept as the row's wet rises; 0 crossfades, 1 keeps full dry",
        (Kind::Freak, "ceiling") => "limit the wet after outputDb",
        (Kind::Freak, "ceilingKneeDb") => "ceiling knee width below ceilingDb; 0 hard-clips",
        (Kind::Freak, "ceilingOnMix") => "true limits after the dry/wet mix; false, the wet only",
        (Kind::Freak, "biasLfoDepth") => "bias LFO depth, in the bands' bias units",
        (Kind::Freak, "biasLfoSpread") => "right or side bias LFO phase lag; 1 is half a cycle",
        (Kind::Gate, "flip") => "invert gate: open below thresholdDb",
        (Kind::Gate, "returnDb") => "closing threshold offset below thresholdDb",
        (Kind::Gate, "releaseMs") => "closing time after holdMs",
        (Kind::VolumeLfo, "sync") => "true follows division; false, rateHz",
        (Kind::Repeat, "variation") => "how far the slice length wanders from grid",
        (Kind::Reverb, "earlyLevel") => "early-reflection level; follows preDelayMs and stops with input",
        (Kind::Reverb, "earlyWidth") => "early width; 0 centered, 1 the full stereo pattern",
        (Kind::Reverb, "earlyOwnLevel") => "early reflections use earlyLevel independently of forwardLevel",
        (Kind::Reverb, "stereoInput") => "input stereo preservation; 0 mono sum, 1 original placement",
        (Kind::Reverb, "width") => "tail width; 0 mono, above 1 boosts sides",
        (Kind::Reverb, "lowDecayTimes") => "decay multiplier below lowCrossoverHz",
        (Kind::Reverb, "highDecayTimes") => "decay multiplier above highCrossoverHz",
        (Kind::Reverb, "modSync") => "true follows modDivision; false, modRateHz",
        (Kind::Reverb, "reverseLevel") => "reverse tail level; swells over decayS into each note",
        (Kind::Reverb, "fadeAfterS") => "wait after the last input peak before fadeDbPerS sets in; 0 is off",
        (Kind::Reverb, "fadeDbPerS") => "extra decay after the fadeAfterS wait, in dB/s; freeze disables it",
        (Kind::Reverb, "tap1Ms" | "tap2Ms" | "tap3Ms" | "tap4Ms" | "tap5Ms") => "the free tap's time; ignores preDelayMs",
        (Kind::Reverb, "tap1Cross" | "tap2Cross" | "tap3Cross" | "tap4Cross" | "tap5Cross") => "the free tap's input at full stereoInput: 0 own channel, 1 opposite",
        (Kind::Reverb, "cubicLines") => "keeps more highs in the tail; fullBand overrides",
        (Kind::Reverb, "plateauMs") => "hold tail level after preDelayMs before decay; 0 is off",
        (Kind::Reverb, "crossMs") => "cross-feed delay for crossFeed and earlyCross",
        (Kind::Reverb, "fullBand") => "keeps highs; dampingHz at 20000 bypasses; overrides cubicLines",
        (Kind::Reverb, "evenDecay") => "keeps decayS consistent across frequencies, sizeTimes, diffusion and mixing",
        (Kind::Sidechain, "holdMs") => "time the duck holds before releaseMs",
        (Kind::Time, "play") => "false slows to a stop; true speeds back up to live input",
        (Kind::Utility, "truePeak") => "4x true-peak detection; needs about two samples of lookaheadMs",
        (Kind::Utility, "releaseMs") => "limiter release; the first stage when tailMs is on",
        (Kind::Utility, "tailMs") => "slow release for tailShare of the reduction; 0 is off",
        (Kind::Utility, "tailShare") => "share of the reduction given to tailMs",
        (Kind::Utility, "lookaheadCurve") => "lookahead ramp: linear in dB, or smooth",
        _ => return None,
    })
}
