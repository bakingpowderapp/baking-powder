pub fn glyph_char(c: char) -> Option<&'static [u8; 9]> {
    GLYPHS.iter().find(|(glyph, _)| *glyph == c).map(|(_, rows)| rows)
}

pub fn pixel(rows: &[u8; 9], x: i32, y: i32) -> bool {
    (rows[y as usize] >> (GLYPH_W - 1 - x)) & 1 == 1
}

pub fn width(text: &str, scale: i32) -> i32 {
    let n = text.chars().count() as i32;
    if n == 0 { 0 } else { (n * ADVANCE - 1) * scale }
}

pub const fn glyphs_in(width: i32, scale: i32) -> usize {
    let glyphs = (width / scale + 1) / ADVANCE;
    if glyphs < 0 { 0 } else { glyphs as usize }
}

pub fn shortened(text: &str, glyphs: usize) -> String {
    if text.chars().count() <= glyphs { text.to_string() } else { text.chars().take(glyphs.saturating_sub(1)).chain(std::iter::once('…')).collect() }
}

pub fn wrapped(text: &str, glyphs: usize) -> Vec<String> {
    let glyphs = glyphs.max(1);
    let mut lines = Vec::new();
    let mut line = String::new();
    for word in text.split_whitespace().flat_map(|word| pieces(word, glyphs)) {
        let taken = line.chars().count();
        if taken > 0 && taken + 1 + word.chars().count() > glyphs {
            lines.push(std::mem::take(&mut line));
        }
        if !line.is_empty() {
            line.push(' ');
        }
        line.push_str(&word);
    }
    if !line.is_empty() {
        lines.push(line);
    }
    lines
}

fn pieces(word: &str, glyphs: usize) -> Vec<String> {
    let chars: Vec<char> = word.chars().collect();
    chars.chunks(glyphs).map(|piece| piece.iter().collect()).collect()
}

pub fn fitted(text: &str, glyphs: usize, lines: usize) -> Vec<String> {
    let mut fitted = wrapped(text, glyphs);
    if fitted.len() > lines {
        let rest = fitted.split_off(lines.max(1) - 1).join(" ");
        fitted.push(shortened(&rest, glyphs));
    }
    fitted
}
